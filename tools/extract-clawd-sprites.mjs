#!/usr/bin/env node
// Builds hooks/clawd-sprites.mjs from YOUR installed Claude desktop app.
//
// The Clawd sprite frames are Anthropic's artwork and ship inside the desktop
// app (app.asar, clawdQuestEngine-*.js). This repo does not redistribute them;
// this script reads them from your own copy, on your machine, and writes the
// file the mascot code imports. No dependencies; read-only on the app.
//
//   node tools/extract-clawd-sprites.mjs [--asar <path to app.asar>] [--out <file>]...
//
// Without --out it writes ../hooks/clawd-sprites.mjs next to this tool.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = ["Laptop", "Desktop", "Thinking", "LookingAround"];
const here = path.dirname(fileURLToPath(import.meta.url));

function args() {
  const a = process.argv.slice(2);
  const o = { asar: null, out: [] };
  for (let i = 0; i < a.length; i += 1) {
    if (a[i] === "--asar") o.asar = a[++i];
    else if (a[i] === "--out") o.out.push(a[++i]);
    else { console.error(`unknown argument: ${a[i]}`); process.exit(2); }
  }
  if (!o.out.length) o.out.push(path.join(here, "..", "hooks", "clawd-sprites.mjs"));
  return o;
}

function findAsar() {
  const found = [];
  const win = "C:\\Program Files\\WindowsApps";
  if (fs.existsSync(win)) {
    try {
      for (const d of fs.readdirSync(win)) {
        if (/^Claude_/.test(d)) found.push(path.join(win, d, "app", "resources", "app.asar"));
      }
    } catch { /* WindowsApps is often unlistable; fall through */ }
  }
  const local = process.env.LOCALAPPDATA;
  if (local) found.push(path.join(local, "AnthropicClaude", "resources", "app.asar"), path.join(local, "Programs", "Claude", "resources", "app.asar"));
  found.push("/Applications/Claude.app/Contents/Resources/app.asar");
  const ok = found.filter((p) => fs.existsSync(p));
  // newest install wins
  ok.sort((a, b) => fs.statSync(b).mtimeMs - fs.statSync(a).mtimeMs);
  return ok[0] ?? null;
}

// Minimal asar reader: 16-byte pickle header, JSON file tree, then file data.
function readEngine(asarPath) {
  const fd = fs.openSync(asarPath, "r");
  try {
    const head = Buffer.alloc(16);
    fs.readSync(fd, head, 0, 16, 0);
    const headerSize = head.readUInt32LE(4);
    const jsonLen = head.readUInt32LE(12);
    const jb = Buffer.alloc(jsonLen);
    fs.readSync(fd, jb, 0, jsonLen, 16);
    const tree = JSON.parse(jb.toString("utf8"));
    let hit;
    (function walk(node) {
      for (const [name, n] of Object.entries(node.files ?? {})) {
        if (n.files) walk(n);
        else if (/^clawdQuestEngine-.*\.js$/.test(name)) hit = n;
      }
    })(tree);
    if (!hit) throw new Error("clawdQuestEngine-*.js not found in the app (the app layout may have changed)");
    const buf = Buffer.alloc(hit.size);
    fs.readSync(fd, buf, 0, hit.size, 8 + headerSize + Number(hit.offset));
    return buf.toString("utf8");
  } finally {
    fs.closeSync(fd);
  }
}

function pick(src, name) {
  const start = src.search(new RegExp(`[,{]${name}:\\{cat:`));
  if (start < 0) throw new Error(`sprite ${name} not found`);
  const seg = src.slice(start, start + 400000);
  const m = (re, what) => {
    const r = seg.match(re);
    if (!r) throw new Error(`${name}: could not read ${what}`);
    return r;
  };
  const [, w] = m(/\bw:(\d+)/, "w");
  const [, h] = m(/\bh:(\d+)/, "h");
  const [, pal] = m(/palette:(\[[^\]]*\])/, "palette");
  const [, base] = m(/base:"([^"]*)"/, "base");
  const [, deltas] = m(/"([^"]*)"\.split\("\("\)/, "deltas");
  const [, a0] = m(/a0:(\[[^\]]*\])/, "a0");
  return { w: +w, h: +h, palette: JSON.parse(pal), a0: JSON.parse(a0), base, deltas };
}

const o = args();
const asar = o.asar ?? findAsar();
if (!asar) {
  console.error("Could not find the Claude desktop app. Pass --asar <path to app.asar>.");
  process.exit(1);
}
const src = readEngine(asar);
const sprites = {};
for (const n of NAMES) sprites[n] = pick(src, n);
const text =
  "// Generated by tools/extract-clawd-sprites.mjs from your own Claude desktop app.\n" +
  "// Clawd sprite frames (c) Anthropic. Local use only: do not commit or redistribute.\n" +
  `export const SPRITES = ${JSON.stringify(sprites)};\n`;
for (const f of o.out) {
  fs.mkdirSync(path.dirname(path.resolve(f)), { recursive: true });
  fs.writeFileSync(f, text);
  console.log(`wrote ${f}`);
}
console.log(`from ${asar}`);
